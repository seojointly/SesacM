public class ForEx {
  public static void main(String[] args) {
    {
      // 1~10
      for (int i = 1; i<=10; i++) {
        System.out.println(i);
      }
    }
    {
      // 10~1
      for (int a = 10; a>=1; a--) {
        System.out.println(a);
        }
      for (int b = 10; b>=1;) {
        System.out.println(b--);
        }
      }
      {
        // 무한루프
        for (;;) {
          System.out.println("Hello World");
      }
    }
  } 
}
